// Logo merek asli (glyph resmi dari Simple Icons, CC0) disimpan sebagai berkas di assets/icons/ dan dipakai
// lewat CSS mask (.brand-icon--*), sehingga tetap bisa diwarnai dan tidak memuat permintaan jaringan tambahan per ikon.
const BRANDS = new Set(["linkedin", "instagram", "whatsapp"]);

export function icon(name, { size = 20, label } = {}) {
  if (BRANDS.has(name)) {
    const a = label ? `role="img" aria-label="${label.replace(/"/g, "")}"` : 'aria-hidden="true"';
    return raw(`<span class="brand-icon brand-icon--${name}" ${a} style="--s:${Number(size) || 20}px"></span>`);
  }
  const body = PATHS[name];
  if (!body) throw new Error(`Ikon tidak dikenal: ${name}`);
  const a11y = label ? `role="img" aria-label="${label.replace(/"/g, "")}"` : 'aria-hidden="true" focusable="false"';
  return raw(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${body}</svg>`
  );
}

